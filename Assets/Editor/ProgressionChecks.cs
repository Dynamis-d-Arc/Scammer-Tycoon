using System;
using ScammerTown;
using UnityEngine;
public static class ProgressionChecks
{
    public static int Run()
    {
        int count=0;Action<bool,string> check=(ok,msg)=>{if(!ok)throw new Exception("PROGRESSION: "+msg);count++;};
        var s=new TycoonState();Management.Ensure(s);var w=s.Current.workers[0];
        float cash=s.cash,normal=Management.Duration(s.Current,w,0,0),chance=Management.Chance(s.Current,w,0);
        check(OfficeProgression.Train(s,w,1) && s.cash==cash-300,"training charges exactly once");
        check(!OfficeProgression.Train(s,w,1) && s.cash==cash-300,"same specialty cannot charge twice");
        check(Mathf.Abs(Management.Duration(s.Current,w,0,0)-normal/1.15f)<.001f,"matching specialty is 15 percent faster");
        check(Mathf.Abs(Management.Chance(s.Current,w,0)-chance-5)<.001f,"specialty adds five success points");
        check(Management.Duration(s.Current,w,0,1)==24,"unmatched specialty has no bonus");
        Management.Start(s,0,w,0);check(!OfficeProgression.Train(s,w,2),"busy employee cannot retrain");
        check(Management.Chance(s.Current,w,3)==100,"repairs remain guaranteed");
        s.cash=100000;s.Current.level=4;
        foreach(string kind in new[]{"lamp","shelf","plant","sofa","rug"})for(int i=0;i<4;i++)
        {var item=FurnitureCatalog.BuyDecoration(s,kind);check(item!=null && RoomLayout.AutoPlace(s.Current,item),"decoration purchase and placement available");}
        check(Mathf.Abs(OfficeProgression.DecorSpeed(s.Current)-.08f)<.0001f,"speed decor caps at eight percent");
        check(Mathf.Abs(OfficeProgression.DecorMorale(s.Current)-.14f)<.0001f,"morale decor caps at 0.14 per second");
        foreach(var item in s.Current.layout)if(FurnitureCatalog.Find(item.kind)!=null)item.placed=false;
        check(OfficeProgression.DecorSpeed(s.Current)==0 && OfficeProgression.DecorMorale(s.Current)==0,"storage removes all bonuses");
        s=new TycoonState();Management.Ensure(s);w=s.Current.workers[0];
        check(!OfficeProgression.Accept(s,2),"advanced contract requires five jobs");
        check(OfficeProgression.Accept(s,0) && !OfficeProgression.Accept(s,1),"only one contract accepted");
        var saved=JsonUtility.FromJson<TycoonState>(JsonUtility.ToJson(s));
        check(Rules.Valid(saved) && saved.contract.target==5,"active contract survives save roundtrip");
        OfficeProgression.CompleteJob(s,1,0,10,(m,a)=>{});OfficeProgression.CompleteJob(s,0,1,10,(m,a)=>{});
        check(s.contract.progress==0,"wrong office and job do not count");
        Management.SetAssignment(s,0,w,0);cash=s.cash;
        Management.Tick(s,61,()=>0,(m,a)=>{});
        check(s.contract==null && s.contractsCompleted==1 && s.cash==cash+5*220+400,"jobs earn normal pay plus single contract reward");
        OfficeProgression.CompleteJob(s,0,0,61,(m,a)=>{});
        check(s.cash==cash+5*220+400 && !OfficeProgression.Accept(s,0),"reward cannot repeat and cooldown applies");
        s=new TycoonState();Management.Ensure(s);OfficeProgression.Accept(s,0);s.paused=true;
        Management.Tick(s,200,()=>0,(m,a)=>{});check(s.elapsed==0 && s.contract!=null,"pause freezes contract timer");
        s.paused=false;Management.Tick(s,121,()=>0,(m,a)=>{});
        check(s.contract==null && s.contractsCompleted==0,"unfinished contract expires without reward");
        s=new TycoonState();Management.Ensure(s);OfficeProgression.Accept(s,0);
        s.contract.progress=4;cash=s.cash;OfficeProgression.CompleteJob(s,0,0,120.01f,(m,a)=>{});
        check(s.contract.progress==4 && s.cash==cash,"late completion cannot receive reward");
        OfficeProgression.CompleteJob(s,0,0,120,(m,a)=>{});
        check(s.contract==null && s.cash==cash+400,"completion at deadline is accepted");
        saved.contract.reward=999999;check(!Rules.Valid(saved),"invalid contract reward rejected");
        s=new TycoonState();Management.Ensure(s);w=s.Current.workers[0];
        check(Management.Jobs[0].name=="Phantom Giveaway" && Management.Jobs[1].name=="Mirage Storefront" && Management.Jobs[2].name=="Moonshot Club","campaign names replace generic jobs without changing save indices");
        Management.SetAssignment(s,0,w,0);Management.Tick(s,12,()=>0,(m,a)=>{});
        check(s.Current.suspicion==4,"successful campaign raises suspicion");
        Management.Ensure(s);check(s.Current.suspicion==4,"saving and migration preserve suspicion");
        OfficeProgression.CampaignResult(s,0,1,false,(m,a)=>{});
        check(s.Current.suspicion==14,"failed campaign adds complaint suspicion");
        OfficeProgression.CampaignResult(s,0,3,true,(m,a)=>{});
        check(s.Current.suspicion==14,"legitimate repair work creates no suspicion");
        saved=JsonUtility.FromJson<TycoonState>(JsonUtility.ToJson(s));
        check(Rules.Valid(saved) && saved.Current.suspicion==14,"suspicion survives save roundtrip");
        saved.Current.suspicion=float.NaN;check(!Rules.Valid(saved),"nonfinite suspicion rejected");
        saved.Current.suspicion=101;check(!Rules.Valid(saved),"out of range suspicion rejected");
        s.Current.suspicion=80;float remaining=w.remaining;cash=s.cash;
        check(OfficeProgression.LayLow(s) && !OfficeProgression.LayLow(s),"lay low cannot repeatedly reset its timer");
        Management.Tick(s,10,()=>0,(m,a)=>{});
        check(Mathf.Abs(s.Current.suspicion-74)<.001f && w.remaining==remaining && s.cash==cash,"lay low reduces suspicion without advancing work or charging");
        s.paused=true;Management.Tick(s,10,()=>0,(m,a)=>{});
        check(s.Current.lockdown==20 && s.Current.suspicion==74 && !OfficeProgression.LayLow(s),"pause freezes suspicion and prevents lay low");
        s.paused=false;Management.Tick(s,20,()=>0,(m,a)=>{});Management.Tick(s,1,()=>0,(m,a)=>{});
        check(w.job==0 && w.remaining>0,"campaign assignment resumes after lay low");
        s.Current.suspicion=99;s.cash=20000;
        check(OfficeProgression.CampaignResult(s,0,2,true,(m,a)=>{}) && s.Current.lockdown==30 && s.Current.suspicion==45 && s.cash==19500,"investigation applies capped penalty and timed freeze");
        s=new TycoonState();Management.Ensure(s);s.Current.suspicion=99;s.cash=100;
        OfficeProgression.CampaignResult(s,0,0,true,(m,a)=>{});
        check(s.cash==95,"investigation charges five percent below cap");
        s=new TycoonState{branchOwned=true};Management.Ensure(s);s.companies[1].suspicion=80;
        OfficeProgression.CampaignResult(s,0,0,true,(m,a)=>{});
        check(s.companies[1].suspicion==80,"office suspicion is independent");
        s.Current.suspicion=99;w=s.Current.workers[0];Management.SetAssignment(s,0,w,0);
        Management.Tick(s,25,()=>0,(m,a)=>{});
        check(s.jobsCompleted==1 && s.Current.lockdown==30,"investigation stops catch-up campaign loop");
        w.job=0;w.duration=12;w.remaining=12;check(OfficeProgression.CampaignActivity(w)=="Campaign live","workstation activity starts with launch");
        w.remaining=6;check(OfficeProgression.CampaignActivity(w)=="Fictional chats active","activity advances with progress");
        w.remaining=1;check(OfficeProgression.CampaignActivity(w)=="Awaiting result","activity shows final stage");
        s=new TycoonState();Management.Ensure(s);w=s.Current.workers[0];cash=s.cash;
        float baseChance=Management.Chance(s.Current,w,0);
        check(OfficeProgression.ValidSkills(0) && OfficeProgression.SkillBonus(s.Current,0)==0,"old saves start with no skill bonus");
        check(!OfficeProgression.UnlockSkill(s,1) && !OfficeProgression.UnlockSkill(s,7) && s.cash==cash,"prerequisites block purchases without charge");
        check(!OfficeProgression.UnlockSkill(s,-1) && !OfficeProgression.UnlockSkill(s,8),"invalid skill indices rejected");
        check(OfficeProgression.UnlockSkill(s,0) && s.cash==cash-400,"starter skill charges once");
        check(!OfficeProgression.UnlockSkill(s,0) && s.cash==cash-400,"owned skill cannot charge again");
        check(Mathf.Abs(Management.Chance(s.Current,w,0)-baseChance-3)<.001f,"starter skill improves actual success chance");
        check(OfficeProgression.UnlockSkill(s,1) && OfficeProgression.SkillBonus(s.Current,0)==7 && OfficeProgression.SkillBonus(s.Current,1)==3,"focus bonus affects only its branch");
        check(OfficeProgression.UnlockSkill(s,4) && OfficeProgression.SkillBonus(s.Current,0)==12,"expertise stacks with starter and focus");
        s.paused=true;cash=s.cash;check(!OfficeProgression.UnlockSkill(s,2) && s.cash==cash,"pause prevents unlocks");s.paused=false;
        s.cash=0;check(!OfficeProgression.UnlockSkill(s,2) && !OfficeProgression.HasSkill(s.Current,2),"insufficient cash cannot unlock a skill");
        s.cash=20000;
        foreach(int node in new[]{2,3,5,6,7})check(OfficeProgression.UnlockSkill(s,node),"remaining branches and mastery unlock in order");
        check(OfficeProgression.SkillBonus(s.Current,0)==15 && OfficeProgression.SkillBonus(s.Current,1)==15 && OfficeProgression.SkillBonus(s.Current,2)==15,"full tree grants fifteen points to each campaign");
        check(Management.Chance(s.Current,w,3)==100 && OfficeProgression.SkillBonus(s.Current,3)==0,"repair shifts remain guaranteed and unaffected");
        w.skill=5;w.mood=100;s.Current.employeeTier=5;w.specialty=1;
        check(Management.Chance(s.Current,w,0)==98,"stacked bonuses respect success cap");
        saved=JsonUtility.FromJson<TycoonState>(JsonUtility.ToJson(s));
        check(Rules.Valid(saved) && saved.Current.campaignSkills==255,"skill tree survives saving");
        check(saved.companies[1].campaignSkills==0,"skills belong only to purchasing office");
        saved.Current.campaignSkills=128;check(!Rules.Valid(saved),"orphan mastery rejected");
        saved.Current.campaignSkills=256;check(!Rules.Valid(saved),"unknown skill bits rejected");
        saved.Current.campaignSkills=-1;check(!Rules.Valid(saved),"negative skill bits rejected");
        s=new TycoonState();Management.Ensure(s);w=s.Current.workers[0];
        check(!OfficeProgression.BeginVoucher(s,w,1),"voucher game requires laptop");
        var laptop=s.Current.layout.Find(it=>it.id==w.station);laptop.kind="laptop";s.Current.desktops=0;s.Current.laptops=1;laptop.id="laptop_0";w.station=laptop.id;
        check(OfficeProgression.BeginVoucher(s,w,1),"placed laptop starts voucher game");
        check(!OfficeProgression.BeginVoucher(s,w,2) && !Management.Start(s,0,w,0),"voucher session prevents duplicate and simultaneous work");
        check(!Management.Assign(s.Current,w,laptop.id) && !OfficeProgression.Train(s,w,1),"desk swaps and retraining blocked during attempt");
        saved=JsonUtility.FromJson<TycoonState>(JsonUtility.ToJson(s));check(Rules.Valid(saved) && saved.Current.workers[0].voucher.symbols.Length==4,"active voucher saves and restores");
        cash=s.cash;int reward=w.voucher.reward;
        s.paused=true;float deadline=w.voucher.deadline;Management.Tick(s,50,()=>0,(m,a)=>{});
        check(s.elapsed==0 && !OfficeProgression.ChooseVoucher(s,w,0,(m,a)=>{}),"pause freezes timer and inputs");s.paused=false;
        for(int i=0;i<4;i++)OfficeProgression.ChooseVoucher(s,w,w.voucher.symbols[w.voucher.progress],(m,a)=>{});
        check(w.voucher==null && s.cash==cash+reward && s.Current.suspicion==4 && w.completed==1,"matching all vouchers pays once and grants experience and suspicion");
        OfficeProgression.FinishVoucher(s,0,w,true,(m,a)=>{});
        check(s.cash==cash+reward && !OfficeProgression.BeginVoucher(s,w,1),"result cannot repay or bypass cooldown");
        s.elapsed=w.voucherReadyAt;w.skill=5;s.Current.campaignSkills=255;
        check(OfficeProgression.BeginVoucher(s,w,2) && w.voucher.allowance==2 && w.voucher.reward==380 && w.voucher.deadline-s.elapsed==55,"employee skill and tree improve tolerance reward and time");
        int wrong=(w.voucher.symbols[0]+1)%5;cash=s.cash;
        OfficeProgression.ChooseVoucher(s,w,wrong,(m,a)=>{});OfficeProgression.ChooseVoucher(s,w,wrong,(m,a)=>{});
        check(w.voucher!=null && w.voucher.mistakes==2,"skilled employee tolerates two mistakes");
        OfficeProgression.ChooseVoucher(s,w,wrong,(m,a)=>{});
        check(w.voucher==null && s.cash==cash && s.Current.suspicion==11,"third mistake fails with suspicion and no payout");
        s.elapsed=w.voucherReadyAt;OfficeProgression.BeginVoucher(s,w,3);w.voucher.deadline=s.elapsed+.5f;
        Management.Tick(s,1,()=>0,(m,a)=>{});check(w.voucher==null && s.Current.suspicion==18,"timeout settles without panel being open");
        s.elapsed=w.voucherReadyAt;OfficeProgression.BeginVoucher(s,w,4);laptop.placed=false;
        Management.Tick(s,.1f,()=>0,(m,a)=>{});check(w.voucher==null,"storing laptop interrupts minigame");
        laptop.placed=true;s.elapsed=w.voucherReadyAt;OfficeProgression.BeginVoucher(s,w,5);s.Current.suspicion=99;
        OfficeProgression.FinishVoucher(s,0,w,false,(m,a)=>{});
        check(s.Current.lockdown==30 && s.Current.suspicion==45,"failed voucher can trigger investigation");
        saved.Current.workers[0].voucher.symbols[0]=9;check(!Rules.Valid(saved),"invalid voucher symbols rejected");
        return count;
    }
}
